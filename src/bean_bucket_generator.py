# * The PNGs will be converted into an npy file. (This workflow will most likely be improved in the future)
from svglib.svglib import svg2rlg
from reportlab.graphics import renderPM



def load_bean_bucket_data(data_dir: Path) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Load empirical pore diameters, throat diameters, and coordinates."""
    import pandas as pd
    pd_df = pd.read_csv(data_dir / "bean_bucket_pd2.csv")
    td_df = pd.read_csv(data_dir / "bean_bucket_td2.csv")
    coord_df = pd.read_csv(data_dir / "bean_bucket_coord.csv")
    pore_diameters = pd_df["pd"].to_numpy()
    throat_diameters = td_df["td"].to_numpy()
    coord = coord_df["coord"].to_numpy()
    return pore_diameters, throat_diameters, coord


