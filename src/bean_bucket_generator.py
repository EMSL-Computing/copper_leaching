"""Generate bean-bucket pore geometry .npy (and matching .png) from pore2chip.

Flow is top-to-bottom by default (as in the original notebook).
Use --flow-direction left-to-right so the main channels span axis 0
(inlet at low index of axis 0), matching the PFLOTRAN x direction.

Example:
    python bean_bucket_generator.py \
      --n-pores-y 10 --n-pores-x 20 \
      --height 400 --width 200 \
      --seed 42 \
      --out my_design.npy

    # Left-to-right flow (common for this project); output shape is (height, width).
    python bean_bucket_generator.py \
      --n-pores-y 10 --n-pores-x 20 \
      --height 200 --width 400 \
      --seed 2 \
      --flow-direction left-to-right \
      --out Chip_Designs/network1/geometry/network1.npy
"""

